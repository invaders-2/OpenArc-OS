import { app, BrowserWindow } from "electron";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { executeCanvasDesktopInput } = require("../electron/canvas-desktop-input.cjs");
app.setPath("userData", fs.mkdtempSync(path.join(os.tmpdir(), "oa-motion-")));
const out = path.resolve("artifacts/canvas-tapnow-compare-20261027/motion-agent.webm");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
setTimeout(() => { console.error("motion-test:timeout"); app.exit(2); }, 45_000).unref();
app.whenReady().then(async () => {
  const sources = await executeCanvasDesktopInput("canvas/capture/sources", {}, null);
  const win = new BrowserWindow({ width: 1440, height: 960, show: true, title: "OpenArc 动效验收", webPreferences: { sandbox: true } });
  await win.loadURL("http://127.0.0.1:5173/artifacts/canvas-tapnow-compare-20261027/openarc-preview.html?motion=1");
  await sleep(1800);
  const selected = await executeCanvasDesktopInput("canvas/capture/selectRecording", { sourceId: sources.sources[0].id }, win.webContents);
  if (!selected.ok) throw new Error(selected.error || "录屏源选择失败");
  await win.webContents.executeJavaScript(`(async()=>{window.__motionStream=await navigator.mediaDevices.getDisplayMedia({video:true,audio:false});window.__motionChunks=[];window.__motionRecorder=new MediaRecorder(window.__motionStream,{mimeType:'video/webm'});window.__motionRecorder.ondataavailable=e=>{if(e.data.size)window.__motionChunks.push(e.data)};window.__motionRecorder.start(200)})()`);
  await sleep(400);
  await win.webContents.executeJavaScript(`document.querySelector('#aPlus')?.click()`); await sleep(700);
  await win.webContents.executeJavaScript(`document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`); await sleep(400);
  await win.webContents.executeJavaScript(`(()=>{const el=document.querySelector('#aiInput');el.value='/';el.dispatchEvent(new Event('input',{bubbles:true}));})()`); await sleep(700);
  await win.webContents.executeJavaScript(`document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`); await sleep(400);
  await win.webContents.executeJavaScript(`document.querySelector('#aFull')?.click()`); await sleep(800);
  await win.webContents.executeJavaScript(`document.querySelector('#aFull')?.click()`); await sleep(500);
  win.setSize(700, 900, true); await sleep(800);
  win.setSize(1440, 960, true); await sleep(800);
  const bytes = await win.webContents.executeJavaScript(`(async()=>{window.__motionRecorder.stop();await new Promise(r=>window.__motionRecorder.onstop=r);window.__motionStream.getTracks().forEach(t=>t.stop());return new Uint8Array(await new Blob(window.__motionChunks,{type:'video/webm'}).arrayBuffer())})()`);
  if (!bytes?.length) throw new Error("动效录屏为空");
  fs.mkdirSync(path.dirname(out), { recursive: true }); fs.writeFileSync(out, Buffer.from(bytes));
  await executeCanvasDesktopInput("canvas/capture/stopRecording", {}, win.webContents);
  console.log(JSON.stringify({ ok: true, output: out, bytes: bytes.length })); app.exit(0);
}).catch((error) => { console.error(error?.stack || error); app.exit(1); });
